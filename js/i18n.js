function i18nGet(lang, path){
  return path.split('.').reduce((obj, key) => (obj && obj[key] !== undefined) ? obj[key] : undefined, I18N[lang]);
}

function applyLanguage(lang){
  if(!I18N[lang]) lang = 'ru';
  document.documentElement.setAttribute('lang', lang === 'uz' ? 'uz' : 'ru');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const value = i18nGet(lang, el.getAttribute('data-i18n'));
    if(value !== undefined) el.innerHTML = value;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const value = i18nGet(lang, el.getAttribute('data-i18n-placeholder'));
    if(value !== undefined) el.setAttribute('placeholder', value);
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  localStorage.setItem('izi-lang', lang);
  window.__iziLang = lang;
}
